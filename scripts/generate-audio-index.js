#!/usr/bin/env node
/**
 * Builds a case-insensitive audio lookup used by the web app.
 * Writes audio-index.js next to the mp3 folders (public/audio and www/public/audio).
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const TARGETS = [
  path.join(ROOT, "public", "audio"),
  path.join(ROOT, "www", "public", "audio"),
];

function buildIndex(audioDir) {
  const files = fs.readdirSync(audioDir).filter((name) => name.endsWith(".mp3"));
  const caseMap = {};
  const allLower = [];

  for (const file of files) {
    const lower = file.toLowerCase();
    allLower.push(lower);
    if (lower !== file) {
      caseMap[lower] = file;
    }
  }

  allLower.sort();
  return { caseMap, allLower, count: files.length };
}

function writeIndexJs(targetDir, index) {
  const outPath = path.join(targetDir, "audio-index.js");
  const body = `// Auto-generated by scripts/generate-audio-index.js — do not edit by hand.
window.AUDIO_CASE_MAP = ${JSON.stringify(index.caseMap)};
window.AUDIO_ALL_FILES = new Set(${JSON.stringify(index.allLower)});
`;
  fs.writeFileSync(outPath, body, "utf8");
  return outPath;
}

function main() {
  for (const dir of TARGETS) {
    if (!fs.existsSync(dir)) {
      console.warn("skip missing dir:", dir);
      continue;
    }
    const index = buildIndex(dir);
    const out = writeIndexJs(dir, index);
    console.log(
      `wrote ${out} (${index.count} files, ${Object.keys(index.caseMap).length} case aliases)`
    );
  }

  const rootIndex = path.join(ROOT, "audio-index.js");
  const wwwIndex = path.join(ROOT, "www", "audio-index.js");
  for (const [srcDir, dest] of [
    [path.join(ROOT, "public", "audio"), rootIndex],
    [path.join(ROOT, "www", "public", "audio"), wwwIndex],
  ]) {
    if (!fs.existsSync(srcDir)) continue;
    const index = buildIndex(srcDir);
    const body = `// Auto-generated by scripts/generate-audio-index.js — do not edit by hand.
window.AUDIO_CASE_MAP = ${JSON.stringify(index.caseMap)};
window.AUDIO_ALL_FILES = new Set(${JSON.stringify(index.allLower)});
`;
    fs.writeFileSync(dest, body, "utf8");
    console.log(`wrote ${dest}`);
  }
}

main();
